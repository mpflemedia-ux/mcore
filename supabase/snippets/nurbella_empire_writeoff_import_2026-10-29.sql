-- 1) Soft-delete ALL currently active products for Nurbella Empire
--    Zero stock, rename code so unique(tenant,code) cannot block re-insert.
UPDATE public.products p
SET
  stock_qty = 0,
  code = CASE
    WHEN p.code IS NULL OR btrim(p.code) = '' THEN 'WO-' || left(replace(p.id::text, '-', ''), 8)
    WHEN p.code LIKE '%-WO-%' THEN p.code
    ELSE left(p.code, 40) || '-WO-' || left(replace(p.id::text, '-', ''), 8)
  END,
  deleted_at = coalesce(p.deleted_at, now()),
  updated_at = now()
FROM public.tenants t
WHERE p.tenant_id = t.id
  AND t.deleted_at IS NULL
  AND t.name ILIKE '%nurbella%empire%'
  AND p.deleted_at IS NULL;

